#!/usr/bin/env node
// Generates CHANGELOG.md from src/data/changelog.json (the source of truth,
// consumed live by the in-app changelog page and footer version stamp).
// Run via `npm run changelog`. CI checks this file is in sync (see ci.yml).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const changelog = JSON.parse(readFileSync(join(root, 'src/data/changelog.json'), 'utf-8'));

const lines = [
  '# Changelog',
  '',
  'Generated from [`src/data/changelog.json`](src/data/changelog.json) — the same data that drives the in-app [changelog page](https://toolkist.app/changelog). Do not edit this file by hand; run `npm run changelog` after changing the JSON.',
  '',
];

for (const entry of changelog) {
  lines.push(`## v${entry.version} — ${entry.date}`, '');
  for (const change of entry.changes) {
    lines.push(`- ${change}`);
  }
  lines.push('');
}

writeFileSync(join(root, 'CHANGELOG.md'), lines.join('\n').trimEnd() + '\n');
console.log('CHANGELOG.md regenerated from src/data/changelog.json');
